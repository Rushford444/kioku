/// Dépôt git sur `main` + magasin (base, graphe, arêtes apprises vides de sens).
fn ready_repo() -> Repo {
    let dir = tempfile::tempdir().expect("tempdir");
    let repo_path = dir.path().join("repo");
    copy_dir(&fixture_crate(), &repo_path);
    fs::write(repo_path.join(".gitignore"), "/target\n").expect("gitignore");
    git(&repo_path, &["init", "-q", "-b", "main"]);
    git(&repo_path, &["add", "-A"]);
    git(&repo_path, &["commit", "-q", "-m", "init"]);
    let commit = git(&repo_path, &["rev-parse", "HEAD"]);
    let store = dir.path().join("store");
    let repo = Repo {
        _dir: dir,
        path: repo_path,
        store,
        commit,
    };
    if rust_analyzer_available() && std::env::var_os("KIOKU_L4_FIXTURE_GRAPH").is_none() {
        let out = run(&mut repo.kioku(&["select", "base", "--repo", "."]));
        assert_eq!(code(&out), 0, "select base: {}", text(&out.stderr));
    } else {
        eprintln!("rust-analyzer absent (ou KIOKU_L4_FIXTURE_GRAPH) : graphe fixture");
        let mut inv = base::collect(&repo.path, &repo.commit, &[]).expect("collect");
        let junit = green_junit(&inv);
        base::apply_junit(&mut inv, &junit).expect("junit");
        let data = fixture_graph();
        inv.graph_digest = Some(data.digest.clone());
        fs::create_dir_all(&repo.store).expect("store");
        fs::write(
            repo.store.join(format!("graph-{}.json", data.digest)),
            graph::to_json(&data).expect("graph json"),
        )
        .expect("write graph");
        base::save(&repo.base_path(), &inv).expect("save base");
    }
    let coverage = repo.store.join("coverage.json");
    fs::write(
        &coverage,
        r#"{"minix::ta ta_uses_a": {"tests/ta.rs": [1]}}"#,
    )
    .expect("coverage");
    let out = run(&mut repo.kioku(&[
        "select",
        "learn",
        "--repo",
        ".",
        "--coverage-json",
        coverage.to_str().expect("utf8"),
    ]));
    assert_eq!(code(&out), 0, "select learn: {}", text(&out.stderr));
    repo
}

fn outcome(journal: &Journal, binary: &str, name: &str) -> Option<Outcome> {
    journal
        .outcomes
        .iter()
        .find(|o| o.test == tid(binary, name))
        .map(|o| o.outcome)
}

fn check_complete(repo: &Repo) -> Journal {
    let journal = repo.journal();
    let inventory: BTreeSet<TestId> = base::load(&repo.base_path())
        .expect("base")
        .binaries
        .iter()
        .flat_map(|b| b.tests.iter().map(|t| tid(&b.binary_id, &t.name)))
        .collect();
    let all: BTreeSet<TestId> = journal.entries.iter().map(|e| e.test.clone()).collect();
    let new: BTreeSet<TestId> = all.difference(&inventory).cloned().collect();
    let known: BTreeSet<TestId> = all.intersection(&inventory).cloned().collect();
    journal::check_complete(&journal, &known, &new)
        .unwrap_or_else(|e| panic!("journal incomplete: {e}"));
    journal
}

fn summary(out: &Output) -> Value {
    serde_json::from_slice(&out.stdout)
        .unwrap_or_else(|e| panic!("json: {e}\n{}", text(&out.stdout)))
}

