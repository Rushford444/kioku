fn write_probe(root: &Path) {
    for (rel, content) in PROBE_FILES {
        let path = root.join(rel);
        fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
        fs::write(path, content).expect("write probe file");
    }
}

fn nextest_list(dir: &Path, filter: Option<&str>) -> Output {
    let mut command = Command::new("cargo");
    clean_env(&mut command)
        .current_dir(dir)
        .args(["nextest", "list", "--locked", "--run-ignored", "all"])
        .args(["--message-format", "json"]);
    if let Some(expr) = filter {
        command.args(["-E", expr]);
    }
    command.output().expect("cargo nextest list runs")
}

/// `(binary_id, nom)` listés par nextest, avec leur `filter-match`.
fn parse_listing(stdout: &[u8]) -> BTreeMap<(String, String), bool> {
    let json: Value = serde_json::from_slice(stdout).expect("nextest json");
    let mut out = BTreeMap::new();
    for (binary, suite) in json["rust-suites"].as_object().expect("suites") {
        for (name, case) in suite["testcases"].as_object().expect("testcases") {
            let matches = case["filter-match"]["status"] == "matches";
            out.insert((binary.clone(), name.clone()), matches);
        }
    }
    out
}

/// Tests que nextest dit sélectionnés par `expr`.
fn nextest_set(dir: &Path, expr: &str) -> BTreeSet<(String, String)> {
    let out = nextest_list(dir, Some(expr));
    assert!(
        out.status.success(),
        "nextest rejette {expr:?} : {}",
        String::from_utf8_lossy(&out.stderr)
    );
    parse_listing(&out.stdout)
        .into_iter()
        .filter_map(|(test, matched)| matched.then_some(test))
        .collect()
}

