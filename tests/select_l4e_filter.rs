//! Lot L4e : le filtre `-E` de l'utilisateur évalué localement, pour ne compiler que les
//! binaires utiles.
//!
//! Trois familles de preuves :
//! 1. **Équivalence avec le vrai nextest** : sur une crate de sonde (lib, binaire, deux tests
//!    d'intégration, id de binaire à tiret), l'ensemble évalué par `FilterSet` est exactement
//!    celui de `cargo nextest list -E … --message-format json` (`filter-match`) ; les
//!    expressions refusées par nextest sont refusées par le parseur.
//! 2. **`restrict_to_user_filter`** sur des plans construits par `plan::plan` : cas de doute
//!    (tests nouveaux, binaires entiers, erreurs), cible `--lib` partagée, plan inchangé quand
//!    l'expression est hors sous-ensemble ; et, contre le vrai nextest, que lister avec les
//!    cibles restreintes donne les mêmes tests qu'avec les cibles d'origine.
//! 3. **De bout en bout** (`kioku test`, mini-crate L4b) : `-E` avec cibles retirées, test neuf
//!    jamais perdu, aucune cible restante (rien n'est compilé, `filtered-out`, exit 0).

