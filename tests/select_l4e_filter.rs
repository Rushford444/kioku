#[test]
fn the_evaluator_selects_exactly_what_real_nextest_selects() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let dir = tmp.path().join("probe");
    write_probe(&dir);
    let all = nextest_list(&dir, None);
    assert!(
        all.status.success(),
        "{}",
        String::from_utf8_lossy(&all.stderr)
    );
    let inventory: BTreeSet<(String, String)> = parse_listing(&all.stdout).into_keys().collect();
    assert_eq!(
        inventory.len(),
        20,
        "inventaire de la sonde : {inventory:?}"
    );
    assert!(SUPPORTED.len() >= 15);

    let mut nonempty = 0;
    for expr in SUPPORTED {
        let parsed = FilterSet::parse(expr).unwrap_or_else(|| panic!("non supporté : {expr:?}"));
        let ours: BTreeSet<(String, String)> = inventory
            .iter()
            .filter(|(binary, name)| parsed.matches(binary, name))
            .cloned()
            .collect();
        let theirs = nextest_set(&dir, expr);
        assert_eq!(ours, theirs, "expression {expr:?}");
        nonempty += usize::from(!theirs.is_empty());
    }
    assert!(
        nonempty >= 40,
        "trop d'expressions vides, la comparaison ne prouverait rien ({nonempty})"
    );
}

#[test]
fn nextest_refuses_an_unknown_binary_id_so_the_parser_exposes_the_ids_it_cites() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let dir = tmp.path().join("probe");
    write_probe(&dir);
    for expr in [
        "binary_id(=nope)",
        "not binary_id(=nope)",
        "test(foo) | binary_id(=nope)",
    ] {
        let out = nextest_list(&dir, Some(expr));
        assert!(!out.status.success(), "{expr:?} accepté par nextest");
        assert!(String::from_utf8_lossy(&out.stderr).contains("didn't match any binary IDs"));
        let parsed = FilterSet::parse(expr).expect("syntaxe valide");
        assert_eq!(parsed.binary_ids(), BTreeSet::from(["nope"]));
    }
}

#[test]
fn what_nextest_rejects_or_the_subset_excludes_is_not_evaluated() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let dir = tmp.path().join("probe");
    write_probe(&dir);
    for expr in REJECTED_BY_NEXTEST {
        assert!(FilterSet::parse(expr).is_none(), "{expr:?} accepté à tort");
        assert!(
            !nextest_list(&dir, Some(expr)).status.success(),
            "nextest accepte finalement {expr:?}"
        );
    }
    for expr in OUT_OF_SUBSET {
        assert!(FilterSet::parse(expr).is_none(), "{expr:?} accepté à tort");
        let out = nextest_list(&dir, Some(expr));
        assert!(
            out.status.success(),
            "{expr:?} devrait être valide pour nextest : {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
}

