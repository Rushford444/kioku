// (a) test unitaire neuf rouge dans un fichier de la lib atteint par l'intégration seule
// ---------------------------------------------------------------------------------------

#[test]
fn a_red_new_unit_test_in_an_existing_lib_file_is_run_and_fails_the_run() {
    let repo = ready_repo();
    repo.feature_branch();
    repo.append("src/d1.rs", RED_TEST);
    let out = run(&mut repo.kioku(&["test", "--repo", ".", "--json"]));
    assert_eq!(code(&out), 1, "{}", dump(&out));
    let summary = summary(&out);
    assert_eq!(summary["status"], "red", "{summary}");
    assert_eq!(summary["counts"]["new"], 1, "{summary}");
    assert!(summary["oracle_ms"].is_u64(), "{summary}");
    let journal = assert_journal_complete(&repo);
    assert_eq!(journal.status, JournalStatus::Red);
    let fresh = entry(&journal, "ownr", "d1::tests::fresh_red");
    assert_eq!(fresh.decision, Decision::Run);
    assert_eq!(fresh.reasons, vec![Reason::NewTest]);
    assert_eq!(
        outcome(&journal, "ownr", "d1::tests::fresh_red"),
        Some(Outcome::Failed)
    );
    // Le test d'intégration atteint `d1.rs` : lancé et vert, comme avant le correctif.
    assert_eq!(
        outcome(&journal, "ownr::it", "uses_d1"),
        Some(Outcome::Passed)
    );
    assert_known_lib_tests_are_not_run(&journal);
}

