//! Correctif A5 : un test NEUF ajouté à un fichier de production existant ne disparaît plus.
//!
//! Défaut reproduit par la vérification indépendante : un `#[test]` ajouté à un fichier de la
//! lib que seuls des tests d'intégration atteignent n'était ni compilé ni listé (la lib n'avait
//! aucun test lancé), donc absent du journal, et `kioku test` finissait `partial-green`.
//!
//! Chaque cas copie une mini-crate (lib `ownr` : `d1.rs` sans test, `other.rs` avec un test
//! sauté et un `#[ignore]`, un binaire d'intégration `it` qui atteint `d1.rs`) dans un dossier
//! temporaire, y fait `git init`, écrit un magasin (inventaire réel de nextest, graphe fixture,
//! arêtes apprises) puis appelle le vrai binaire `kioku`.
//!
//! Preuves : (a) test unitaire neuf rouge → `run`/`failed`, exit 1 ; (b) vert → `passed`,
//! `new=1`, exit 0 ; (c) neuf `#[ignore]` → journalisé `ignored`, exit 0 ; (d) avec `-E` qui ne
//! le sélectionne pas → `filtered-out`, jamais absent, et avec `-E` qui le sélectionne → rouge ;
//! (e) l'oracle de complétude refuse un run que nextest ne liste pas comme nous le prévoyons.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use kioku::select::base;
use kioku::select::graph;
use kioku::select::journal::{self, Journal, JournalStatus, Outcome};
use kioku::select::{BaseInventory, BaseStatus, Decision, GRAPH_SCHEMA, GraphData, Reason, TestId};
use serde_json::Value;

const GRAPH_DIGEST: &str = "fixture-a5-1";

const CARGO_TOML: &str = "[package]\nname = \"ownr\"\nversion = \"0.0.1\"\nedition = \"2024\"\npublish = false\n\n# Racine de workspace propre : cette fixture n'appartient pas au workspace de kioku.\n[workspace]\n";
const CARGO_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"ownr\"\nversion = \"0.0.1\"\n";
const LIB_RS: &str = "pub mod d1;\npub mod other;\n";
const D1_RS: &str = "#[must_use]\npub fn one() -> u32 {\n    1\n}\n";
const OTHER_RS: &str = "#[must_use]\npub fn two() -> u32 {\n    2\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn unrelated() {\n        assert_eq!(super::two(), 2);\n    }\n\n    #[test]\n    #[ignore = \"ignoré par construction\"]\n    fn heavy() {\n        assert_eq!(super::two(), 2);\n    }\n}\n";
const IT_RS: &str = "#[test]\nfn uses_d1() {\n    assert_eq!(ownr::d1::one(), 1);\n}\n";

const RED_TEST: &str = "\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn fresh_red() {\n        panic!(\"a5-red\");\n    }\n}\n";
const GREEN_TEST: &str = "\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn fresh_green() {\n        assert_eq!(super::one(), 1);\n    }\n}\n";
const IGNORED_TEST: &str = "\n#[cfg(test)]\nmod tests {\n    #[test]\n    #[ignore = \"nouveau et ignoré\"]\n    fn fresh_ignored() {\n        panic!(\"never run\");\n    }\n}\n";

